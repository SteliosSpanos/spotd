package server

import (
	"context"

	"google.golang.org/grpc"
	"google.golang.org/grpc/codes"
	"google.golang.org/grpc/status"

	pb "github.com/SteliosSpanos/spotd/gen/spotd/v1"
	"github.com/SteliosSpanos/spotd/internal/jobs"
	"github.com/SteliosSpanos/spotd/internal/spotify"
)

type PlaylistLister interface {
	MyPlaylists(ctx context.Context) ([]spotify.Playlist, error)
}

type JobRunners interface {
	Runner(kind jobs.Kind, playlistID string) (jobs.Runner, error)
}

type JobManager interface {
	Start(kind jobs.Kind, playlistID string, run jobs.Runner) (string, error)
	Subscribe(id string) (<-chan jobs.Progress, func(), error)
	Cancel(id string) error
}

// Implements the gRPC server interface generated by protocol buffers
type Playlists struct {
	pb.UnimplementedPlaylistServiceServer
	api     PlaylistLister
	runners JobRunners
	jobs    JobManager
}

func NewPlaylists(api PlaylistLister, runners JobRunners, jm JobManager) *Playlists {
	return &Playlists{api: api, runners: runners, jobs: jm}
}

func (s *Playlists) ListPlaylists(ctx context.Context, _ *pb.ListPlaylistsRequest) (*pb.ListPlaylistsResponse, error) {
	pls, err := s.api.MyPlaylists(ctx)
	if err != nil {
		return nil, err
	}

	out := make([]*pb.Playlist, 0, len(pls))
	for _, p := range pls {
		out = append(out, &pb.Playlist{Id: p.ID, Name: p.Name, TrackCount: int32(p.Items.Total)})
	}

	return &pb.ListPlaylistsResponse{Playlists: out}, nil
}

func (s *Playlists) StartJob(_ context.Context, req *pb.StartJobRequest) (*pb.StartJobResponse, error) {
	// FIX: use jobs.ValidID instead of a duplicate regex
	if !jobs.ValidID(req.GetPlaylistId()) {
		return nil, status.Error(codes.InvalidArgument, "playlist_id must be 22 char Spotify id")
	}

	kind, err := kindFromProto(req.GetKind())
	if err != nil {
		return nil, err
	}

	run, err := s.runners.Runner(kind, req.GetPlaylistId())
	if err != nil {
		return nil, err
	}

	id, err := s.jobs.Start(kind, req.GetPlaylistId(), run)
	if err != nil {
		return nil, err
	}

	return &pb.StartJobResponse{JobId: id}, nil
}

func (s *Playlists) WatchJob(req *pb.WatchJobRequest, stream grpc.ServerStreamingServer[pb.WatchJobResponse]) error {
	ch, cancel, err := s.jobs.Subscribe(req.GetJobId())
	if err != nil {
		return err
	}
	defer cancel()

	ctx := stream.Context() // Tracks if the CLI user pressed Ctrl+C to close the terminal

	for {
		select {
		case <-ctx.Done():
			return ctx.Err()
		case p, ok := <-ch:
			if !ok {
				return nil
			}

			if err := stream.Send(progressToProto(p)); err != nil {
				return err
			}
		}
	}
}

// FIX: CancelJob was declared in the proto but never implemented
func (s *Playlists) CancelJob(_ context.Context, req *pb.CancelJobRequest) (*pb.CancelJobResponse, error) {
	if req.GetJobId() == "" {
		return nil, status.Error(codes.InvalidArgument, "job_id is required")
	}

	if err := s.jobs.Cancel(req.GetJobId()); err != nil {
		return nil, err
	}

	return &pb.CancelJobResponse{}, nil
}

func kindFromProto(k pb.JobKind) (jobs.Kind, error) {
	switch k {
	case pb.JobKind_JOB_KIND_BACKUP:
		return jobs.Backup, nil
	case pb.JobKind_JOB_KIND_RESTORE:
		return jobs.Restore, nil
	case pb.JobKind_JOB_KIND_DEDUPE:
		return jobs.Dedupe, nil
	case pb.JobKind_JOB_KIND_SORT:
		return jobs.Sort, nil
	default:
		return 0, status.Errorf(codes.InvalidArgument, "unknown job kind %d", k)
	}
}

func progressToProto(p jobs.Progress) *pb.WatchJobResponse {
	var st pb.JobState

	switch p.State {
	case jobs.Pending:
		st = pb.JobState_JOB_STATE_PENDING
	case jobs.Running:
		st = pb.JobState_JOB_STATE_RUNNING
	case jobs.Succeeded:
		st = pb.JobState_JOB_STATE_SUCCEEDED
	case jobs.Failed:
		st = pb.JobState_JOB_STATE_FAILED
	case jobs.Canceled:
		st = pb.JobState_JOB_STATE_CANCELED
	}

	return &pb.WatchJobResponse{
		JobId:   p.JobID,
		State:   st,
		Done:    int32(p.Done),
		Total:   int32(p.Total),
		Message: p.Message,
		Error:   p.Err,
	}
}
